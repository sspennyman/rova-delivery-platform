import assert from 'node:assert/strict';
import {searchWixOrders} from '../worker/wix-search.js';
import {withinOrderWindow,outsideDailyOrderWindow,ORDER_WINDOW_MS} from '../public/order-window.js';
const now=Date.now(), recent=new Date(now-3600000).toISOString();
assert.ok(withinOrderWindow(new Date(now-ORDER_WINDOW_MS).toISOString(),now));
assert.ok(!withinOrderWindow(new Date(now-ORDER_WINDOW_MS-1).toISOString(),now));
assert.ok(!withinOrderWindow(new Date(now+1).toISOString(),now));
assert.ok(!withinOrderWindow('',now));
assert.ok(outsideDailyOrderWindow({source:{system:'wix',createdDate:'2024-01-01'}},now));
assert.ok(!outsideDailyOrderWindow({source:{system:'manual',createdDate:'2024-01-01'}},now));
const config={configured:true,authorization:'fixture-only',siteId:'fixture-site',orderStatuses:['APPROVED'],paymentStatuses:['PAID'],fulfillmentStatuses:['NOT_FULFILLED','PARTIALLY_FULFILLED','FULFILLED'],lookbackDays:9999,limit:1};
const requests=[];
const mock=async(url,options)=>{
 const q=JSON.parse(options.body).search;requests.push(q);
 if(q.cursorPaging.cursor)return Response.json({orders:[{id:'old-open',createdDate:'2024-01-01'},{id:'page-two',createdDate:recent}],metadata:{hasNext:false}});
 assert.ok(Math.abs(Date.now()-Date.parse(q.filter.createdDate.$gte)-ORDER_WINDOW_MS)<1000,'every query starts exactly 24 hours ago regardless of old config');assert.deepEqual(Object.keys(q.filter.createdDate),['$gte'],'Wix accepts one date comparison per field; upper bound enforced locally');
 const paid={id:'recent-paid',createdDate:recent,paymentStatus:'PAID'};
 if(q.filter.paymentStatus.$in.length===1)return Response.json({orders:[paid],metadata:{hasNext:false}});
 assert.ok(q.filter.paymentStatus.$in.includes('NOT_PAID'));assert.ok(!q.filter.paymentStatus.$in.includes('FULLY_REFUNDED'));
 return Response.json({orders:[paid,{id:'offline-new',createdDate:recent,paymentStatus:'NOT_PAID'},{id:'bad-date',createdDate:''}],metadata:{hasNext:true,cursors:{next:'next'}}});
};
const orders=await searchWixOrders(config,mock);
assert.deepEqual(orders.map(x=>x.id).sort(),['offline-new','page-two','recent-paid']);
assert.equal(orders.find(x=>x.id==='offline-new').paymentStatus,'NOT_PAID');
assert.ok(requests.every(x=>x.cursorPaging.limit===100));
assert.ok(!requests.find(x=>x.cursorPaging.cursor).filter);
await assert.rejects(()=>searchWixOrders(config,async()=>Response.json({orders:[],metadata:{hasNext:true,cursors:{next:'same'}}})),/did not advance/);
await assert.rejects(()=>searchWixOrders(config,async()=>Response.json({message:'No access'},{status:403})),/Wix 403/);
await assert.rejects(()=>searchWixOrders(config,async()=>Response.json({})),/invalid orders/);
console.log('Wix 24-hour window passed: query bounds, cutoff boundaries, old/invalid/future exclusion, offline payments, cursor paging and deduplication.');
