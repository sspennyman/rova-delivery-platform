console.log("Mileage checks passed: auto start/stop, GPS gaps, replay, ownership, privacy, classification, weekly submission, approval locks, export and timezone.");

// Weekly bulk review accepts saved GPS endpoints, but never hides an actual gap.
const sample = { ...structuredClone(t), id: "weekly-one", week: "2026-09-14", date: "2026-09-15", state: "complete", category: "unclassified", purpose: "", from: "", to: "", reviewedAt: null, flags: [], distanceKm: 2.345, audit: [] };
const second = { ...structuredClone(sample), id: "weekly-two", flags: ["Some GPS fixes were unusable"], distanceKm: 1.234 };
db.mileageTrips.push(sample, second);
assert.equal((await request("/api/mileage/review", { tripIds: [sample.id, "missing"], category: "business", purpose: "Deliveries" })).status, 404);
assert.equal(sample.category, "unclassified", "batch fails atomically if a trip is missing");
assert.equal((await request("/api/mileage/review", { tripIds: [sample.id], category: "business", purpose: "Deliveries" }, "POST", { role: "driver", driverId: "b" })).status, 404);
assert.equal((await request("/api/mileage/review", { tripIds: [sample.id, second.id], category: "business" })).status, 400, "one shared purpose is required");
assert.equal((await request("/api/mileage/review", { tripIds: [sample.id, second.id], category: "business", purpose: "Customer deliveries" })).status, 200);
assert.ok(sample.reviewedAt);
assert.ok(second.reviewedAt, "discarded weak fixes alone are not a trip-level blocker");
assert.equal((await request("/api/mileage/reports", { week: sample.week, expectedKmRate: .72 })).status, 409, "concurrent rate changes require reconfirmation");
assert.equal((await request("/api/mileage/reports", { week: sample.week, expectedKmRate: .81 })).status, 201);
const weekly = db.mileageReports.at(-1);
assert.match(weekly.items[0].from, /^GPS:/, "recorded endpoints need no retyping");
assert.equal(weekly.totalAmount, 2.90, "total is the sum of rounded per-trip amounts");
const csv = await (await request(`/api/mileage/reports/${weekly.id}/export.csv`, undefined, "GET", dispatcher)).text();
assert.match(csv, /Rate CAD per km/);
assert.match(csv, /Reimbursement CAD/);
assert.match(csv, /"TOTAL"/);
assert.match(csv, /"2.90"/);
assert.equal((await request("/api/mileage/review", { tripIds: [sample.id], category: "personal" })).status, 409, "bulk changes respect report locks");
const gapTrip = { ...structuredClone(sample), id: "weekly-gap", week: "2026-09-07", flags: ["GPS gap: distance may be incomplete"], reviewedAt: null };
db.mileageTrips.push(gapTrip);
await request("/api/mileage/review", { tripIds: [gapTrip.id], category: "business", purpose: "Deliveries" });
assert.equal(gapTrip.reviewedAt, null, "classifying a trip does not acknowledge missing distance");
assert.equal((await request("/api/mileage/reports", { week: gapTrip.week })).status, 400);
await request("/api/mileage/review", { tripIds: [gapTrip.id], category: "business", purpose: "Deliveries", acknowledgeWarnings: true });
assert.ok(gapTrip.reviewedAt);
db.drivers[0].defaultRate = null;
assert.equal((await request("/api/mileage/reports", { week: gapTrip.week })).status, 400, "missing rate is not silently replaced");
db.drivers[0].defaultRate = 0;
assert.equal((await request("/api/mileage/reports", { week: gapTrip.week })).status, 201, "explicit zero rate is respected");
assert.equal(db.mileageReports.at(-1).totalAmount, 0);
assert.equal((await request("/api/mileage/reports", { week: "2026-09-31" })).status, 400);
console.log("Weekly-review checks passed: atomic bulk classification, GPS endpoints, warnings, report rate snapshots, exact totals, CSV, zero/missing rates and ownership.");
