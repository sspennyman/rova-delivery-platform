import assert from "node:assert/strict";
import { ingestPoints, mileageSnapshot, handleMileage, mileageCsv, localDay, mileageWeek } from "../worker/mileage.js";

const now = Date.now();
const base = now - 3600_000;
const deviceId = "test-device-00000001";
const db = { drivers: [{ id: "a", name: "Test Driver", vehicle: "Test car", defaultRate: 0.72 }, { id: "b", name: "Other Driver" }] };
mileageSnapshot(db, "a");
Object.assign(db.mileageTracking.a, { enabled: true, enabledAt: new Date(base - 1000).toISOString(), deviceId, source: "android" });
let live = 0;
const points = Array.from({ length: 11 }, (_, i) => ({ seq: i + 1, at: base + i * 20000, lat: 45.42 + i * .001, lng: -75.7, accuracy: 5, speed: 5.5 }));
const send = p => ingestPoints(db, "a", { deviceId, points: p }, now, () => live++);
send(points.slice(0, 4));
assert.equal(db.mileageTrips.length, 1, "driving starts a trip without dispatch or manual start");
assert.equal(db.mileageTrips[0].category, "unclassified", "no automatic tax/business assumption");
assert.ok(db.mileageTrips[0].previewPath.length > 1, "automatic trips retain an authentic GPS map preview");
send(points.slice(4));
const tracked = db.mileageTrips[0].distanceKm;
assert.ok(tracked > 1.1 && tracked < 1.12, "GPS distance includes movement before detection threshold");
send(points);
assert.equal(db.mileageTrips[0].distanceKm, tracked, "retry is idempotent");
assert.equal(live, 0, "offline replay must not overwrite a live delivery map");
send(Array.from({ length: 10 }, (_, i) => ({ ...points.at(-1), seq: 12 + i, at: base + 220000 + i * 20000, speed: 0 })));
assert.equal(db.mileageTrips[0].state, "complete", "stationary GPS automatically ends a trip");
assert.equal(db.mileageTrips[0].endedAt, new Date(base + 200000).toISOString(), "stopped waiting time is not driving time");
assert.throws(() => ingestPoints(db, "a", { deviceId: "another-device", points }, now), /another device/);
assert.throws(() => send(Array(101).fill(points[0])), /100 GPS/);
assert.equal(mileageSnapshot(db, "b").trips.length, 0, "driver isolation");
assert.equal(mileageSnapshot(db).trips, undefined, "dispatch gets no private ledger");
assert.equal(mileageSnapshot(db).previewPath,undefined,"private paths never enter the dispatcher snapshot");
assert.equal(localDay("2026-09-21T02:00:00Z"), "2026-09-20", "reports use local Toronto date");
assert.equal(mileageWeek("2026-09-20"), "2026-09-14", "weeks start Monday, including timezone boundary");

let saves = 0;
const session = { role: "driver", driverId: "a", name: "Test" };
async function request(path, body, method = "POST", who = session) {
  const url = new URL(`https://test.invalid${path}`);
  const req = new Request(url, { method, headers: body === undefined ? {} : { "Content-Type": "application/json" }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  return handleMileage({ request: req, url, db, session: who, save: async () => saves++, isDispatcher: s => s?.role === "dispatcher", onLive: () => {} });
}
const t = db.mileageTrips[0];
assert.equal((await request("/api/mileage", undefined, "GET", null)).status, 401);
assert.equal((await request("/api/mileage/preferences", { businessPurpose: " Customer deliveries " })).status, 200);
assert.equal(mileageSnapshot(db, "a").preferences.businessPurpose, "Customer deliveries");
assert.equal(mileageSnapshot(db, "b").preferences.businessPurpose, "", "default purposes are driver-scoped");
assert.equal(mileageSnapshot(db).preferences, undefined, "dispatch cannot read private preferences");
assert.equal(t.category, "unclassified", "saving a purpose never classifies driving automatically");
assert.equal((await request("/api/mileage/preferences", { businessPurpose: 42 })).status, 400);
assert.equal((await request("/api/mileage/preferences", { businessPurpose: "" })).status, 200, "preference can be cleared");
assert.equal(mileageSnapshot(db, "a").preferences.businessPurpose, "");
assert.equal((await request(`/api/mileage/trips/${t.id}`, { category: "business" }, "PATCH", { role: "driver", driverId: "b" })).status, 404);
assert.equal((await request("/api/mileage/reports", { week: t.week })).status, 400, "unclassified trips block submission");
assert.equal((await request(`/api/mileage/trips/${t.id}`, { category: "business", from: "Depot", to: "Customer", purpose: "Flower delivery" }, "PATCH")).status, 200);
const privateTrip = { ...structuredClone(t), id: "private-trip", category: "personal", from: "PRIVATE HOME", to: "PRIVATE DESTINATION", purpose: "PRIVATE PURPOSE" };
db.mileageTrips.push(privateTrip);
assert.equal((await request("/api/mileage/reports", { week: t.week })).status, 201);
const dispatcher = { role: "dispatcher", name: "Manager" };
const shared = await (await request("/api/mileage", undefined, "GET", dispatcher)).json();
assert.ok(!JSON.stringify(shared).includes("PRIVATE"), "personal destinations, purposes, distances are not shared");
assert.equal(shared.reports[0].items.length, 1);
assert.equal((await request("/api/mileage/reports", { week: t.week })).status, 409, "prevent duplicate report submission");
assert.equal((await request(`/api/mileage/trips/${t.id}`, { category: "personal" }, "PATCH")).status, 409, "submitted report locks source trips");
const report = db.mileageReports[0];
assert.equal(report.kmRate, 0.72, "report snapshots driver rate");
assert.equal(report.items[0].kmRate, 0.72);
assert.equal(report.totalAmount, Math.round(report.items[0].distanceKm * .72 * 100) / 100);
db.drivers[0].defaultRate = 0.81;
assert.equal(report.kmRate, 0.72, "changing driver rate never rewrites old reports");
assert.equal((await request(`/api/mileage/reports/${report.id}`, { status: "approved" }, "PATCH")).status, 409, "driver cannot self-approve");
assert.equal((await request(`/api/mileage/reports/${report.id}`, { status: "withdrawn" }, "PATCH")).status, 200);
assert.equal((await request(`/api/mileage/trips/${t.id}`, { purpose: "Updated purpose" }, "PATCH")).status, 200);
assert.equal(report.items[0].purpose, "Flower delivery", "historical report is immutable after source edits");
assert.equal((await request("/api/mileage/reports", { week: t.week })).status, 201);
const finalReport = db.mileageReports.at(-1);
assert.equal((await request(`/api/mileage/reports/${finalReport.id}`, { status: "approved" }, "PATCH", dispatcher)).status, 200);
assert.equal((await request(`/api/mileage/reports/${finalReport.id}`, { status: "withdrawn" }, "PATCH")).status, 409);
assert.equal((await request("/api/mileage/export.csv?year=2026", undefined, "GET", dispatcher)).status, 403, "dispatch cannot export personal ledger");
assert.equal((await request(`/api/mileage/reports/${finalReport.id}/export.csv`, undefined, "GET", { role: "driver", driverId: "b" })).status, 404);
assert.match(mileageCsv([{ ...t, purpose: '=HYPERLINK("bad")' }]), /'=HYPERLINK/, "CSV formula injection is neutralized");

