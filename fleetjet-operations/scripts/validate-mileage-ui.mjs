function validMarkup(html) {
  const stack = [], voidTags = new Set(["input", "br", "hr", "img", "meta", "link"]);
  for (const match of html.matchAll(/<\/?([a-z][\w-]*)\b[^>]*>/gi)) {
    const tag = match[1].toLowerCase();
    if (voidTags.has(tag)) continue;
    if (match[0].startsWith("</")) assert.equal(stack.pop(), tag, `balanced ${tag}`); else stack.push(tag);
  }
  assert.deepEqual(stack, [], "all markup closes");
}
