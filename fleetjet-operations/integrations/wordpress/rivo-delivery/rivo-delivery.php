final class Rivo_Delivery_Connector {
    const OPTION = 'rivo_delivery_connection';
    const STATUS = 'rivo_delivery_status';
    const HOOK = 'rivo_delivery_sync_order';
    public static function boot() {
        add_action( 'admin_menu', array( __CLASS__, 'menu' ) );
        add_action( 'admin_post_rivo_delivery_save', array( __CLASS__, 'save' ) );
        add_action( 'admin_post_rivo_delivery_sync', array( __CLASS__, 'scan' ) );
        add_action( 'admin_post_rivo_delivery_test', array( __CLASS__, 'test' ) );
        add_action( 'admin_post_rivo_delivery_disconnect', array( __CLASS__, 'disconnect' ) );
        foreach ( array( 'woocommerce_new_order', 'woocommerce_update_order', 'woocommerce_order_status_changed' ) as $hook ) {
            add_action( $hook, array( __CLASS__, 'enqueue' ), 20, 1 );
        }
        add_action( self::HOOK, array( __CLASS__, 'send_order' ), 10, 2 );
    }
    public static function menu() {
        add_submenu_page( 'woocommerce', __( 'Rivo Delivery', 'rivo-delivery' ), __( 'Rivo Delivery', 'rivo-delivery' ), 'manage_woocommerce', 'rivo-delivery', array( __CLASS__, 'render' ) );
    }
    public static function connection() {
        $value = get_option( self::OPTION, array() );
        return is_array( $value ) ? $value : array();
    }
    public static function enabled() {
        $c = self::connection();
        return ! empty( $c['consent'] ) && ! empty( $c['endpoint'] ) && ! empty( $c['token'] );
    }
    public static function parse_connection( $input ) {
        $parts = wp_parse_url( trim( $input ) );
        if ( ! is_array( $parts ) || 'https' !== ( $parts['scheme'] ?? '' ) || 'app.floraljet.llc' !== ( $parts['host'] ?? '' ) || isset( $parts['port'] ) || isset( $parts['user'] ) || isset( $parts['pass'] ) || isset( $parts['fragment'] ) || ! preg_match( '#^/api/integrations/webhook/[A-Za-z0-9_-]{1,160}$#', $parts['path'] ?? '' ) ) {
            return new WP_Error( 'rivo_invalid_url', __( 'Paste the Universal webhook URL generated by your Rivo workspace.', 'rivo-delivery' ) );
        }
        parse_str( $parts['query'] ?? '', $query );
        $token = $query['token'] ?? '';
        if ( ! is_string( $token ) || ! preg_match( '/^[A-Za-z0-9_.~-]{24,512}$/', $token ) ) {
            return new WP_Error( 'rivo_invalid_token', __( 'The connection URL must include its Rivo token.', 'rivo-delivery' ) );
        }
        return array( 'endpoint' => 'https://app.floraljet.llc' . $parts['path'], 'token' => $token );
    }
    private static function authorize( $action ) {
        if ( ! current_user_can( 'manage_woocommerce' ) ) { wp_die( esc_html__( 'You do not have permission to manage this connection.', 'rivo-delivery' ), '', array( 'response' => 403 ) ); }
        check_admin_referer( $action );
    }
    private static function finish( $message ) {
        update_option( self::STATUS, array( 'message' => $message, 'at' => gmdate( 'c' ) ), false );
        wp_safe_redirect( admin_url( 'admin.php?page=rivo-delivery' ) );
        exit;
    }
    public static function save() {
        self::authorize( 'rivo_delivery_save' );
        $connection = self::connection();
        $input = isset( $_POST['rivo_connection_url'] ) && is_string( $_POST['rivo_connection_url'] ) ? trim( wp_unslash( $_POST['rivo_connection_url'] ) ) : '';
        if ( '' !== $input ) {
            $parsed = self::parse_connection( $input );
            if ( is_wp_error( $parsed ) ) { self::finish( $parsed->get_error_message() ); }
            $connection = $parsed;
        }
        $connection['consent'] = isset( $_POST['rivo_consent'] ) && '1' === $_POST['rivo_consent'];
        update_option( self::OPTION, $connection, false );
        self::finish( self::enabled() ? __( 'Connected. New and changed recent orders will be queued for Rivo.', 'rivo-delivery' ) : __( 'Order sharing is off. No order data will be sent.', 'rivo-delivery' ) );
    }
    public static function disconnect() {
        self::authorize( 'rivo_delivery_disconnect' );
        delete_option( self::OPTION );
        if ( function_exists( 'as_unschedule_all_actions' ) ) { as_unschedule_all_actions( self::HOOK ); }
        self::finish( __( 'Disconnected. Existing records in Rivo are unchanged.', 'rivo-delivery' ) );
    }
    public static function enqueue( $order_id, $attempt = 0 ) {
        if ( ! self::enabled() || ! function_exists( 'wc_get_order' ) ) { return; }
        $order = wc_get_order( absint( $order_id ) );
        if ( ! $order || ! self::recent( $order ) ) { return; }
        $args = array( absint( $order_id ), absint( $attempt ) );
        if ( function_exists( 'as_has_scheduled_action' ) && as_has_scheduled_action( self::HOOK, $args, 'rivo-delivery' ) ) { return; }
        $delay = $attempt ? min( 3600, 60 * pow( 2, $attempt - 1 ) ) : 1;
        if ( function_exists( 'as_schedule_single_action' ) ) {
            as_schedule_single_action( time() + $delay, self::HOOK, $args, 'rivo-delivery', true );
        } elseif ( ! wp_next_scheduled( self::HOOK, $args ) ) {
            wp_schedule_single_event( time() + $delay, self::HOOK, $args );
        }
    }
    public static function recent( $order ) {
        $date = $order->get_date_created();
        return $date && $date->getTimestamp() >= time() - DAY_IN_SECONDS && $date->getTimestamp() <= time();
    }
    public static function payload( $order ) {
        $items = array();
        foreach ( $order->get_items() as $item ) {
            $items[] = array( 'quantity' => $item->get_quantity(), 'name' => $item->get_name() );
            if ( count( $items ) >= 12 ) { break; }
        }
        return array(
            'id' => (string) $order->get_id(), 'number' => (string) $order->get_order_number(),
            'createdAt' => gmdate( 'c', $order->get_date_created()->getTimestamp() ),
            'customerName' => trim( $order->get_shipping_first_name() . ' ' . $order->get_shipping_last_name() ),
            'phone' => method_exists( $order, 'get_shipping_phone' ) ? $order->get_shipping_phone() : '',
            'shippingAddress' => array( 'address1' => $order->get_shipping_address_1(), 'address2' => $order->get_shipping_address_2(), 'city' => $order->get_shipping_city(), 'state' => $order->get_shipping_state(), 'postcode' => $order->get_shipping_postcode(), 'country' => $order->get_shipping_country() ),
            'items' => $items, 'paymentStatus' => $order->is_paid() ? 'paid' : 'pending',
            'fulfillmentStatus' => $order->get_status(), 'status' => $order->get_status(),
        );
    }
    private static function request( $orders ) {
        if ( ! self::enabled() ) { return new WP_Error( 'rivo_disabled', __( 'Enable order sharing before testing or syncing.', 'rivo-delivery' ) ); }
        $c = self::connection();
        $validated = self::parse_connection( $c['endpoint'] . '?token=' . rawurlencode( $c['token'] ) );
        if ( is_wp_error( $validated ) ) { return $validated; }
        // The destination is fixed to Rivo. Never send a connection token through a redirect.
        return wp_safe_remote_post( $c['endpoint'], array( 'timeout' => 15, 'redirection' => 0, 'sslverify' => true, 'headers' => array( 'Content-Type' => 'application/json', 'x-fleetjet-token' => $c['token'] ), 'body' => wp_json_encode( array( 'orders' => $orders ) ) ) );
    }
    public static function send_order( $order_id, $attempt = 0 ) {
        if ( ! self::enabled() || ! function_exists( 'wc_get_order' ) ) { return; }
        $order = wc_get_order( absint( $order_id ) );
        if ( ! $order || ! self::recent( $order ) || ! in_array( $order->get_status(), array( 'pending', 'processing', 'on-hold', 'completed', 'cancelled', 'refunded', 'failed' ), true ) ) { return; }
        $payload = self::payload( $order );
        if ( '' === trim( $payload['shippingAddress']['address1'] ) ) { return; }
        $response = self::request( array( $payload ) );
        $code = is_wp_error( $response ) ? 0 : wp_remote_retrieve_response_code( $response );
        if ( $code >= 200 && $code < 300 ) {
            update_option( self::STATUS, array( 'message' => __( 'Recent order changes reached Rivo.', 'rivo-delivery' ), 'at' => gmdate( 'c' ) ), false );
            return;
        }
        update_option( self::STATUS, array( 'message' => __( 'An order could not reach Rivo. Check the connection and retry the past 24 hours.', 'rivo-delivery' ), 'at' => gmdate( 'c' ) ), false );
        if ( $attempt < 5 && ( 0 === $code || 429 === $code || $code >= 500 ) ) { self::enqueue( $order_id, $attempt + 1 ); }
    }
    public static function scan() {
        self::authorize( 'rivo_delivery_sync' );
        if ( ! self::enabled() || ! function_exists( 'wc_get_orders' ) ) { self::finish( __( 'Enable the connection and activate WooCommerce first.', 'rivo-delivery' ) ); }
        $ids = wc_get_orders( array( 'limit' => 100, 'paginate' => true, 'page' => 1, 'return' => 'ids', 'date_created' => '>' . ( time() - DAY_IN_SECONDS ), 'orderby' => 'date', 'order' => 'DESC' ) );
        $pages = is_object( $ids ) ? (int) $ids->max_num_pages : 0;
        if ( $pages > 50 ) { self::finish( __( 'More than 5,000 recent orders need review. Contact Rivo before importing this backlog.', 'rivo-delivery' ) ); }
        for ( $page = 1; $page <= max( 1, $pages ); $page++ ) {
            $batch = 1 === $page ? $ids : wc_get_orders( array( 'limit' => 100, 'paginate' => true, 'page' => $page, 'return' => 'ids', 'date_created' => '>' . ( time() - DAY_IN_SECONDS ), 'orderby' => 'date', 'order' => 'DESC' ) );
            foreach ( is_object( $batch ) ? $batch->orders : array() as $id ) { self::enqueue( $id ); }
        }
        self::finish( __( 'Recent orders are queued. WooCommerce Scheduled Actions processes the imports.', 'rivo-delivery' ) );
    }
    public static function test() {
        self::authorize( 'rivo_delivery_test' );
        $response = self::request( array() );
        $code = is_wp_error( $response ) ? 0 : wp_remote_retrieve_response_code( $response );
        self::finish( $code >= 200 && $code < 300 ? __( 'Connection accepted by Rivo. No customer data was sent by this test.', 'rivo-delivery' ) : __( 'Connection test failed. Check the saved URL and sharing consent.', 'rivo-delivery' ) );
    }
    public static function render() {
        if ( ! current_user_can( 'manage_woocommerce' ) ) { return; }
        require __DIR__ . '/settings.php';
    }
}
Rivo_Delivery_Connector::boot();
register_deactivation_hook( __FILE__, function () {
    $connection = Rivo_Delivery_Connector::connection();
    $connection['consent'] = false;
    update_option( Rivo_Delivery_Connector::OPTION, $connection, false );
    if ( function_exists( 'as_unschedule_all_actions' ) ) { as_unschedule_all_actions( Rivo_Delivery_Connector::HOOK ); }
} );
